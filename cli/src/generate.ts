/**
 * Render the derived files that live in ~/.hivemind:
 *   - .env               container env (consumed by docker-compose + the app)
 *   - rclone.conf        the Drive remote definition (scoped to the hive folder)
 *   - docker-compose.yml the per-node three-service stack
 *
 * The three `render*` functions are PURE (ResolvedConfig -> string) so they can be
 * unit-tested without any filesystem access. `writeGeneratedFiles` is the only
 * side-effecting function; it just persists what the pure renderers produce.
 */
import { chmodSync, mkdirSync, writeFileSync } from 'node:fs';
import type { ResolvedConfig } from './config.js';
import { composePath, envPath, hivemindDir, rcloneConfPath } from './paths.js';

/** Fixed in-container mount target (host path is configurable; container path is not). */
export const CONTAINER_HIVEMIND_PATH = '/mnt/hivemind';
/** Fixed local Postgres DSN (data volume is LOCAL, never on the mount). */
export const DATABASE_URL =
  'postgresql+asyncpg://teamtrail:teamtrail@postgres:5432/hivemind';
export const EMBEDDING_MODEL = 'BAAI/bge-small-en-v1.5';
export const EMBEDDING_DIM = 384;
export const APP_IMAGE_REPO = 'ghcr.io/browserstack/hivemind';

/**
 * Render ~/.hivemind/.env — the container environment (SPEC §10).
 * Keys exactly: OWNER_HANDLE, ROSTER, HIVEMIND_PATH, DATABASE_URL, EMBEDDING_MODEL,
 * EMBEDDING_DIM, EXPORT_INTERVAL_SEC, IMPORT_INTERVAL_SEC, MCP_HOST, MCP_PORT.
 */
export function renderEnvFile(cfg: ResolvedConfig): string {
  const lines = [
    '# Generated by @browserstack/hivemind — do not edit by hand.',
    '# Regenerated from ~/.hivemind.conf on every `hivemind setup` / `hivemind up`.',
    `OWNER_HANDLE=${cfg.ownerHandle}`,
    `ROSTER=${cfg.roster.join(',')}`,
    `HIVEMIND_PATH=${CONTAINER_HIVEMIND_PATH}`,
    `DATABASE_URL=${DATABASE_URL}`,
    `EMBEDDING_MODEL=${EMBEDDING_MODEL}`,
    `EMBEDDING_DIM=${EMBEDDING_DIM}`,
    `EXPORT_INTERVAL_SEC=${cfg.exportIntervalSec}`,
    `IMPORT_INTERVAL_SEC=${cfg.importIntervalSec}`,
    'MCP_HOST=0.0.0.0',
    `MCP_PORT=${cfg.mcpPort}`,
  ];
  return lines.join('\n') + '\n';
}

/**
 * Render ~/.hivemind/rclone.conf. The remote is scoped to the shared hive folder
 * via `root_folder_id` (extracted from gdrive_folder_url). The OAuth token is the
 * only secret; `setup` supplies it after headless auth. When absent an empty token
 * line is written (the file is completed by `rclone config`).
 */
export function renderRcloneConf(cfg: ResolvedConfig, token = ''): string {
  const lines = [
    '# Generated by @browserstack/hivemind.',
    '# Holds the per-developer Google Drive OAuth token — the only secret on disk.',
    '[hivemind]',
    'type = drive',
    'scope = drive',
    `root_folder_id = ${cfg.folderId}`,
    `token = ${token}`,
  ];
  return lines.join('\n') + '\n';
}

/**
 * Render ~/.hivemind/docker-compose.yml (SPEC §11). The app image tag is pinned
 * inline to the resolved config; OWNER_HANDLE / MCP_PORT are interpolated by
 * Compose from the sibling .env at runtime. The Postgres volume is LOCAL.
 */
export function renderDockerCompose(cfg: ResolvedConfig): string {
  return `# Generated by @browserstack/hivemind — regenerated from ~/.hivemind.conf.
services:
  gdrive:
    image: rclone/rclone:latest
    container_name: hivemind-gdrive
    cap_add:
      - SYS_ADMIN
    devices:
      - /dev/fuse
    security_opt:
      - apparmor:unconfined
    environment:
      RCLONE_CONFIG: /config/rclone.conf
    volumes:
      - ./rclone.conf:/config/rclone.conf:ro
      - type: bind
        source: ${cfg.mountPath}
        target: ${CONTAINER_HIVEMIND_PATH}
        bind:
          propagation: rshared
    command:
      - mount
      - hivemind:
      - ${CONTAINER_HIVEMIND_PATH}
      - --allow-other
      - --allow-non-empty
      - --dir-cache-time
      - 10s
      - --poll-interval
      - 10s
      - --vfs-cache-mode
      - writes
      - --umask
      - "022"
    healthcheck:
      test: ["CMD", "test", "-d", "${CONTAINER_HIVEMIND_PATH}/\${OWNER_HANDLE}"]
      interval: 10s
      timeout: 5s
      retries: 12
      start_period: 30s
    restart: unless-stopped

  postgres:
    image: pgvector/pgvector:pg16
    container_name: hivemind-postgres
    environment:
      POSTGRES_USER: teamtrail
      POSTGRES_PASSWORD: teamtrail
      POSTGRES_DB: hivemind
    volumes:
      - hivemind-pgdata:/var/lib/postgresql/data
    healthcheck:
      test: ["CMD-SHELL", "pg_isready -U teamtrail -d hivemind"]
      interval: 5s
      timeout: 5s
      retries: 20
      start_period: 10s
    restart: unless-stopped

  app:
    image: ${APP_IMAGE_REPO}:${cfg.imageTag}
    container_name: hivemind-app
    depends_on:
      gdrive:
        condition: service_healthy
      postgres:
        condition: service_healthy
    env_file:
      - ./.env
    ports:
      - "\${MCP_PORT}:\${MCP_PORT}"
    volumes:
      - type: bind
        source: ${cfg.mountPath}
        target: ${CONTAINER_HIVEMIND_PATH}
        bind:
          propagation: rslave
    restart: unless-stopped

volumes:
  hivemind-pgdata:
    driver: local
`;
}

/** Options for {@link writeGeneratedFiles}. */
export interface WriteOptions {
  /** Existing rclone OAuth token to preserve/embed (from headless auth). */
  token?: string;
  /** Skip rewriting rclone.conf (e.g. when `rclone config` already wrote it). */
  skipRclone?: boolean;
}

/** Paths written by {@link writeGeneratedFiles}. */
export interface GeneratedPaths {
  env: string;
  rclone?: string;
  compose: string;
}

/**
 * Persist the derived files into ~/.hivemind (creating it if needed). Side-effecting
 * wrapper around the pure renderers.
 */
export function writeGeneratedFiles(cfg: ResolvedConfig, opts: WriteOptions = {}): GeneratedPaths {
  mkdirSync(hivemindDir(), { recursive: true });

  const env = envPath();
  writeFileSync(env, renderEnvFile(cfg), 'utf8');

  const compose = composePath();
  writeFileSync(compose, renderDockerCompose(cfg), 'utf8');

  const result: GeneratedPaths = { env, compose };

  if (!opts.skipRclone) {
    const rclone = rcloneConfPath();
    writeFileSync(rclone, renderRcloneConf(cfg, opts.token ?? ''), 'utf8');
    // rclone.conf holds a secret; restrict permissions.
    chmodSync(rclone, 0o600);
    result.rclone = rclone;
  }

  return result;
}
