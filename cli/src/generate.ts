/**
 * Render the derived files that live in ~/.hivemind:
 *   - .env               container env (consumed by docker-compose + the app)
 *   - rclone.conf        the Drive remote definition (scoped to the hive folder)
 *   - docker-compose.yml the per-node three-service stack
 *
 * The three `render*` functions are PURE (ResolvedConfig -> string) so they can be
 * unit-tested without any filesystem access. `writeGeneratedFiles` is the only
 * side-effecting function; it just persists what the pure renderers produce.
 */
import { cpSync, chmodSync, existsSync, mkdirSync, rmSync, writeFileSync } from 'node:fs';
import type { ResolvedConfig } from './config.js';
import {
  bundledAppDir,
  composePath,
  envPath,
  hivemindAppDir,
  hivemindDir,
  rcloneConfPath,
} from './paths.js';

/** Fixed in-container mount target (host path is configurable; container path is not). */
export const CONTAINER_HIVEMIND_PATH = '/mnt/hivemind';
/** Fixed local Postgres DSN (data volume is LOCAL, never on the mount). */
export const DATABASE_URL =
  'postgresql+asyncpg://teamtrail:teamtrail@postgres:5432/hivemind';
/** Embedded SQLite DSN for the sqlite persistence backend (db on a LOCAL docker volume). */
export const SQLITE_DATABASE_URL = 'sqlite+aiosqlite:////data/hivemind.db';
/** The real (production) embedder, baked into the image when embeddings=true. */
export const EMBEDDING_MODEL = 'BAAI/bge-small-en-v1.5';
/** Sentinel selecting the deterministic torch-free FakeEmbedder (embeddings=false). */
export const FAKE_EMBEDDING_MODEL = 'fake';
export const EMBEDDING_DIM = 384;
/** Local image tag; the app is built from bundled source, never pulled from a registry. */
export const APP_IMAGE_NAME = 'hivemind';

/**
 * Render ~/.hivemind/.env — the container environment (SPEC §10).
 * Keys exactly: OWNER_HANDLE, ROSTER, HIVEMIND_PATH, DATABASE_URL, EMBEDDING_MODEL,
 * EMBEDDING_DIM, EXPORT_INTERVAL_SEC, IMPORT_INTERVAL_SEC, MCP_HOST, MCP_PORT.
 */
export function renderEnvFile(cfg: ResolvedConfig): string {
  const lines = [
    '# Generated by hivemind — do not edit by hand.',
    '# Regenerated from ~/.hivemind.conf on every `hivemind setup` / `hivemind up`.',
    `OWNER_HANDLE=${cfg.ownerHandle}`,
    `ROSTER=${cfg.roster.join(',')}`,
    `HIVEMIND_PATH=${CONTAINER_HIVEMIND_PATH}`,
    `DATABASE_URL=${cfg.persistence === 'sqlite' ? SQLITE_DATABASE_URL : DATABASE_URL}`,
    `EMBEDDING_MODEL=${cfg.embeddings ? EMBEDDING_MODEL : FAKE_EMBEDDING_MODEL}`,
    `EMBEDDING_DIM=${EMBEDDING_DIM}`,
    `EXPORT_INTERVAL_SEC=${cfg.exportIntervalSec}`,
    `IMPORT_INTERVAL_SEC=${cfg.importIntervalSec}`,
    'MCP_HOST=0.0.0.0',
    `MCP_PORT=${cfg.mcpPort}`,
  ];
  return lines.join('\n') + '\n';
}

/**
 * Render ~/.hivemind/rclone.conf. The remote is scoped to the shared hive folder
 * via `root_folder_id` (extracted from gdrive_folder_url). The OAuth token is the
 * only secret; `setup` supplies it after headless auth. When absent an empty token
 * line is written (the file is completed by `rclone config`).
 */
export function renderRcloneConf(cfg: ResolvedConfig, token = ''): string {
  const lines = [
    '# Generated by hivemind.',
    '# Holds the per-developer Google Drive OAuth token — the only secret on disk.',
    '[hivemind]',
    'type = drive',
    'scope = drive',
    `root_folder_id = ${cfg.folderId}`,
    `token = ${token}`,
  ];
  return lines.join('\n') + '\n';
}

/** Render the pgvector Postgres service block (shared by both backends). */
function postgresServiceBlock(): string {
  return `  postgres:
    image: pgvector/pgvector:pg16
    container_name: hivemind-postgres
    environment:
      POSTGRES_USER: teamtrail
      POSTGRES_PASSWORD: teamtrail
      POSTGRES_DB: hivemind
    volumes:
      - hivemind-pgdata:/var/lib/postgresql/data
    healthcheck:
      test: ["CMD-SHELL", "pg_isready -U teamtrail -d hivemind"]
      interval: 5s
      timeout: 5s
      retries: 20
      start_period: 10s
    restart: unless-stopped`;
}

/**
 * The app service's image directive: build LOCALLY from the bundled ./app source
 * (staged into ~/.hivemind/app) and tag it `hivemind:<version>`. `docker compose
 * up` builds the image on first run (tag absent), reuses it afterwards, and
 * rebuilds when a package upgrade bumps the tag. Nothing is pulled from a registry.
 * INSTALL_EMBEDDINGS bakes the real torch embedder only when embeddings=true.
 */
function appImageBuild(cfg: ResolvedConfig): string {
  const install = cfg.embeddings ? '1' : '0';
  return `    build:
      context: ./app
      args:
        INSTALL_EMBEDDINGS: "${install}"
    image: ${APP_IMAGE_NAME}:${cfg.imageTag}`;
}

/**
 * Render ~/.hivemind/docker-compose.yml (SPEC §11). Dispatches on the mount
 * backend: the rclone FUSE stack (three services) or the Google Drive for
 * Desktop stack (two services — the host GDFD folder is bind-mounted directly).
 */
export function renderDockerCompose(cfg: ResolvedConfig): string {
  if (cfg.persistence === 'sqlite') return renderComposeSqlite(cfg);
  return cfg.mountBackend === 'gdrive_desktop'
    ? renderComposeGdriveDesktop(cfg)
    : renderComposeRclone(cfg);
}

/**
 * Google Drive for Desktop backend: no rclone/FUSE container and no OAuth token.
 * The Drive-for-Desktop app already syncs the folder locally, so the app simply
 * bind-mounts the user's `hivemind/` folder (gdriveDesktopPath) into the container.
 */
function renderComposeGdriveDesktop(cfg: ResolvedConfig): string {
  return `# Generated by hivemind — regenerated from ~/.hivemind.conf.
# Backend: gdrive_desktop — Google Drive for Desktop syncs the hive folder; the
# app bind-mounts it directly (no rclone container, no OAuth token on disk).
services:
${postgresServiceBlock()}

  app:
${appImageBuild(cfg)}
    container_name: hivemind-app
    depends_on:
      postgres:
        condition: service_healthy
    env_file:
      - ./.env
    ports:
      - "\${MCP_PORT}:\${MCP_PORT}"
    volumes:
      - type: bind
        source: ${cfg.gdriveDesktopPath}
        target: ${CONTAINER_HIVEMIND_PATH}
    restart: unless-stopped

volumes:
  hivemind-pgdata:
    driver: local
`;
}

/**
 * rclone FUSE backend (three services). The app image tag is pinned inline; the
 * gdrive service mounts Drive via rclone with the per-user OAuth token in
 * rclone.conf; OWNER_HANDLE / MCP_PORT are interpolated from the sibling .env.
 */
function renderComposeRclone(cfg: ResolvedConfig): string {
  return `# Generated by hivemind — regenerated from ~/.hivemind.conf.
services:
  gdrive:
    image: rclone/rclone:latest
    container_name: hivemind-gdrive
    cap_add:
      - SYS_ADMIN
    devices:
      - /dev/fuse
    security_opt:
      - apparmor:unconfined
    environment:
      RCLONE_CONFIG: /config/rclone.conf
    volumes:
      - ./rclone.conf:/config/rclone.conf:ro
      - type: bind
        source: ${cfg.mountPath}
        target: ${CONTAINER_HIVEMIND_PATH}
        bind:
          propagation: rshared
    command:
      - mount
      - "hivemind:"
      - ${CONTAINER_HIVEMIND_PATH}
      - --allow-other
      - --allow-non-empty
      - --dir-cache-time
      - 10s
      - --poll-interval
      - 10s
      - --vfs-cache-mode
      - writes
      - --umask
      - "022"
    healthcheck:
      test: ["CMD", "test", "-d", "${CONTAINER_HIVEMIND_PATH}/\${OWNER_HANDLE}"]
      interval: 10s
      timeout: 5s
      retries: 12
      start_period: 30s
    restart: unless-stopped

  postgres:
    image: pgvector/pgvector:pg16
    container_name: hivemind-postgres
    environment:
      POSTGRES_USER: teamtrail
      POSTGRES_PASSWORD: teamtrail
      POSTGRES_DB: hivemind
    volumes:
      - hivemind-pgdata:/var/lib/postgresql/data
    healthcheck:
      test: ["CMD-SHELL", "pg_isready -U teamtrail -d hivemind"]
      interval: 5s
      timeout: 5s
      retries: 20
      start_period: 10s
    restart: unless-stopped

  app:
${appImageBuild(cfg)}
    container_name: hivemind-app
    depends_on:
      gdrive:
        condition: service_healthy
      postgres:
        condition: service_healthy
    env_file:
      - ./.env
    ports:
      - "\${MCP_PORT}:\${MCP_PORT}"
    volumes:
      - type: bind
        source: ${cfg.mountPath}
        target: ${CONTAINER_HIVEMIND_PATH}
        bind:
          propagation: rslave
    restart: unless-stopped

volumes:
  hivemind-pgdata:
    driver: local
`;
}

/**
 * SQLite backend: embedded sqlite-vec, no database server. The db lives on a LOCAL
 * docker volume (hivemind-dbdata) — never the Drive mount — to avoid cloud-sync
 * corruption. The hive folder is still mounted per the mount backend (rclone FUSE
 * service, or a gdrive_desktop bind). The sqlite DATABASE_URL comes from .env.
 */
function renderComposeSqlite(cfg: ResolvedConfig): string {
  const rclone = cfg.mountBackend !== 'gdrive_desktop';
  const gdriveService = rclone
    ? `  gdrive:
    image: rclone/rclone:latest
    container_name: hivemind-gdrive
    cap_add:
      - SYS_ADMIN
    devices:
      - /dev/fuse
    security_opt:
      - apparmor:unconfined
    environment:
      RCLONE_CONFIG: /config/rclone.conf
    volumes:
      - ./rclone.conf:/config/rclone.conf:ro
      - type: bind
        source: ${cfg.mountPath}
        target: ${CONTAINER_HIVEMIND_PATH}
        bind:
          propagation: rshared
    command:
      - mount
      - "hivemind:"
      - ${CONTAINER_HIVEMIND_PATH}
      - --allow-other
      - --allow-non-empty
      - --dir-cache-time
      - 10s
      - --poll-interval
      - 10s
      - --vfs-cache-mode
      - writes
      - --umask
      - "022"
    healthcheck:
      test: ["CMD", "test", "-d", "${CONTAINER_HIVEMIND_PATH}/\${OWNER_HANDLE}"]
      interval: 10s
      timeout: 5s
      retries: 12
      start_period: 30s
    restart: unless-stopped

`
    : '';
  const appDeps = rclone
    ? `    depends_on:
      gdrive:
        condition: service_healthy
`
    : '';
  const appMount = rclone
    ? `      - type: bind
        source: ${cfg.mountPath}
        target: ${CONTAINER_HIVEMIND_PATH}
        bind:
          propagation: rslave`
    : `      - type: bind
        source: ${cfg.gdriveDesktopPath}
        target: ${CONTAINER_HIVEMIND_PATH}`;
  return `# Generated by hivemind — regenerated from ~/.hivemind.conf (persistence: sqlite).
# Embedded SQLite + sqlite-vec: no database server. The db is on a LOCAL docker
# volume (never the Drive mount) to avoid cloud-sync corruption.
services:
${gdriveService}  app:
${appImageBuild(cfg)}
    container_name: hivemind-app
${appDeps}    env_file:
      - ./.env
    ports:
      - "\${MCP_PORT}:\${MCP_PORT}"
    volumes:
      - hivemind-dbdata:/data
${appMount}
    restart: unless-stopped

volumes:
  hivemind-dbdata:
    driver: local
`;
}

/** Options for {@link writeGeneratedFiles}. */
export interface WriteOptions {
  /** Existing rclone OAuth token to preserve/embed (from headless auth). */
  token?: string;
  /** Skip rewriting rclone.conf (e.g. when `rclone config` already wrote it). */
  skipRclone?: boolean;
}

/** Paths written by {@link writeGeneratedFiles}. */
export interface GeneratedPaths {
  env: string;
  rclone?: string;
  compose: string;
}

/**
 * Persist the derived files into ~/.hivemind (creating it if needed). Side-effecting
 * wrapper around the pure renderers.
 */
export function writeGeneratedFiles(cfg: ResolvedConfig, opts: WriteOptions = {}): GeneratedPaths {
  mkdirSync(hivemindDir(), { recursive: true });

  const env = envPath();
  writeFileSync(env, renderEnvFile(cfg), 'utf8');

  const compose = composePath();
  writeFileSync(compose, renderDockerCompose(cfg), 'utf8');

  const result: GeneratedPaths = { env, compose };

  // The gdrive_desktop backend never uses rclone, so no rclone.conf is written.
  const skipRclone = opts.skipRclone || cfg.mountBackend === 'gdrive_desktop';
  if (!skipRclone) {
    const rclone = rcloneConfPath();
    writeFileSync(rclone, renderRcloneConf(cfg, opts.token ?? ''), 'utf8');
    // rclone.conf holds a secret; restrict permissions.
    chmodSync(rclone, 0o600);
    result.rclone = rclone;
  }

  return result;
}

/**
 * Stage the bundled Python app source into ~/.hivemind/app so the generated
 * compose can build the image locally (`build: context: ./app`). Cleaned and
 * re-copied every time so a package upgrade refreshes the source. This is what
 * makes the stack self-sufficient — no image is pulled from a registry.
 *
 * `srcDir` defaults to the bundled app in the package; overridable for tests.
 * Throws if the bundle is missing (i.e. the package was not built).
 */
export function stageAppSource(
  srcDir: string = bundledAppDir(),
  destDir: string = hivemindAppDir(),
): string {
  if (!existsSync(srcDir)) {
    throw new Error(
      `Hivemind app source not found at ${srcDir} — the package was not built. ` +
        'Run `npm run build` in the cli package (or reinstall a published build).',
    );
  }
  rmSync(destDir, { recursive: true, force: true });
  mkdirSync(hivemindDir(), { recursive: true });
  cpSync(srcDir, destDir, { recursive: true });
  return destDir;
}
